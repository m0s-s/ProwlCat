#!/usr/bin/env python3
"""Regenerate src/mascot_data.rs: Fang's pixel grids, rasterised from the master drawing.

The polygons below are the same ones used by the vector master (the SVG on the design canvas),
in a 200x200 box and left-right symmetric. Each pixel gets one class:

    0 empty    1 body     3 eye     4 dark detail (ears, brow, forehead notch)
    5 fang     6 nose     7 mouth interior

Needs Pillow:  python tools/gen_mascot.py > src/mascot_data.rs
"""
import sys

from PIL import Image, ImageDraw

SS = 8  # supersampling factor
SIL = [(100, 50), (74, 42), (50, 6), (40, 58), (14, 80), (28, 92), (8, 120), (28, 124),
       (20, 154), (54, 150), (68, 176), (100, 190)]


def mirror_path(pts):
    return [(200 - x, y) for x, y in reversed(pts)]


def both(pts):
    return [pts, [(200 - x, y) for x, y in pts]]


LAYERS = [  # (class, polygons), painted in order
    (1, [SIL + mirror_path(SIL)]),
    (4, both([(56, 20), (66, 44), (47, 52)])
        + both([(44, 70), (98, 90), (98, 99), (50, 86)])
        + [[(100, 56), (94, 80), (100, 76), (106, 80)]]),
    (3, both([(56, 94), (96, 103), (92, 110), (60, 106)])),
    (6, [[(92, 116), (108, 116), (100, 127)]]),
    (7, [[(64, 136), (136, 136), (122, 160), (100, 168), (78, 160)]]),
    (5, both([(72, 136), (85, 136), (79, 160)]) + both([(87, 166), (95, 166), (91, 152)])),
]


def raster(w, h):
    sx, sy = w / 200.0, h / 200.0
    masks = []
    for cls, polys in LAYERS:
        im = Image.new("L", (w * SS, h * SS), 0)
        d = ImageDraw.Draw(im)
        for p in polys:
            d.polygon([(x * sx * SS, y * sy * SS) for x, y in p], fill=255)
        masks.append((cls, im.resize((w, h), Image.BOX).load()))
    rows = []
    for y in range(h):
        row = ""
        for x in range(w):
            c = 0
            for cls, px in masks:
                if px[x, y] >= 128:
                    c = cls
            row += str(c)
        # The rasteriser's edge rules differ left to right by a pixel; Fang is symmetric by design,
        # so keep the left half and mirror it.
        half = row[: w // 2]
        rows.append(half + half[::-1])
    return rows


def emit(name, doc, rows):
    print(f"/// {doc}")
    print(f"pub const {name}: [&str; {len(rows)}] = [")
    for r in rows:
        print(f'    "{r}",')
    print("];\n")


print("//! Generated by tools/gen_mascot.py from the master drawing. Do not edit by hand.\n")
emit("SMALL", "24 x 20 pixels (24 columns x 10 rows once paired into half blocks).", raster(24, 20))
emit("BIG", "48 x 40 pixels (48 columns x 20 rows), used by the splash screen.", raster(48, 40))
sys.stdout.flush()
