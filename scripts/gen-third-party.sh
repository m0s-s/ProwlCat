#!/usr/bin/env bash
# Regenerate THIRD-PARTY-NOTICES.md from the dependencies that end up in the prowlcat binary.
set -eu
cd "$(dirname "$0")/.."
{
  cat <<'HEAD'
# Third-party notices

ProwlCat is licensed under the AGPL-3.0-or-later (see `LICENSE`). The released binaries include
the open-source libraries below, each under the license shown. Their full license texts are
distributed with their source on crates.io; the license policy that every dependency must meet
is in `deny.toml`.

Generated by `scripts/gen-third-party.sh`; do not edit by hand.

| Crate | Version | License |
|-------|---------|---------|
HEAD
  cargo tree -p prowlcat-cli -e normal --prefix none --locked --format '{p}|{l}' \
    | grep -v '^prowlcat-' | sed 's/ (proc-macro)//; s/ (\*)//' | sort -u \
    | awk -F'|' '{ split($1, a, " "); name=a[1]; ver=a[2]; sub(/^v/, "", ver); printf "| [%s](https://crates.io/crates/%s) | %s | %s |\n", name, name, ver, $2 }'
} > THIRD-PARTY-NOTICES.md
echo "wrote THIRD-PARTY-NOTICES.md ($(grep -c '^| \[' THIRD-PARTY-NOTICES.md) crates)"
